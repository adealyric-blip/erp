// seed-flats.ts — seed the 12 core blanks (plan/08) as owned templates.
// Run:  node scripts/seed-flats.ts [--tenant <uuid>] [--size M]
//        [--sql-out <path>] [--svg-dir <dir>] [--supabase]
//
// Why esbuild: Node's type-stripping requires explicit `.ts` extensions in
// relative imports, which would break Next typecheck; esbuild bundles the
// pure-TS flat-gen package to a single .mjs file and the script imports it.
//
// Modes:
//   SQL (default): writes the SVGs to --svg-dir and a re-runnable SQL file
//     to --sql-out (apply with psql against the LOCAL database; the file
//     upserts the owned license, design_assets rows and templates —
//     print_areas written back from the generated rects).
//   --supabase: same, but uploads the SVGs to design-private and inserts
//     the rows via SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY
//     (local Supabase or a throwaway project — never the live project).
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEV_TENANT = '11111111-1111-4111-8111-111111111111';
const GENERATOR_VERSION = 'flat-gen/1';

const args = new Map<string, string>();
for (let i = 2; i < process.argv.length; i++) {
  const a = process.argv[i];
  if (a.startsWith('--')) args.set(a.slice(2), process.argv[++i] ?? 'true');
}
const tenant = args.get('tenant') ?? DEV_TENANT;
const size = args.get('size') ?? 'M';
const svgDir = resolve(args.get('svg-dir') ?? join(REPO, 'docs', 'phase2-proof', 'lane-b', 'flats'));
const sqlOut = resolve(args.get('sql-out') ?? join(REPO, 'docs', 'phase2-proof', 'lane-b', 'seed-flats.sql'));
const useSupabase = args.has('supabase');

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

// 1. Bundle flat-gen with esbuild (no TS loader needed for the script itself).
const bundle = join(tmpdir(), `flat-gen-seed-${process.pid}.mjs`);
execFileSync(join(REPO, 'node_modules', '.bin', 'esbuild'), [
  join(REPO, 'src', 'lib', 'flat-gen', 'index.ts'),
  '--bundle',
  '--format=esm',
  '--platform=node',
  `--outfile=${bundle}`,
], { stdio: 'inherit' });
const fg = (await import(bundle)) as {
  BLANKS: Array<{
    id: string; name: string; category: string; archetype: string; views: string[];
    block: unknown; style: unknown;
  }>;
  generateFlat: (blank: unknown, size: string) => {
    views: { view: string; svg: string; widthMm: number; heightMm: number; printAreas: Record<string, unknown> }[];
  };
  validateFlatSvg: (svg: string) => { ok: boolean; errors: string[] };
};

// 2. Generate + validate every blank, write the SVGs.
mkdirSync(svgDir, { recursive: true });
const generated: {
  blank: { id: string; name: string; category: string; archetype: string; views: string[]; block: unknown; style: unknown };
  views: { view: string; svg: string; widthMm: number; heightMm: number; printAreas: Record<string, unknown> }[];
}[] = [];
for (const blank of fg.BLANKS) {
  const flat = fg.generateFlat(blank, size);
  for (const view of flat.views) {
    const res = fg.validateFlatSvg(view.svg);
    if (!res.ok) throw new Error(`generated ${blank.id}/${view.view} failed validation: ${res.errors.join('; ')}`);
    const dir = join(svgDir, blank.id);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, `${view.view}.svg`), view.svg);
  }
  generated.push({ blank, views: flat.views });
  console.log(`generated ${blank.id}: ${flat.views.map((v) => v.view).join(', ')}`);
}

// 3. Emit the SQL (license + assets + templates, all upserts).
const lines: string[] = [];
lines.push('-- seed-flats.sql — 12 core blanks as owned templates (flat-gen/1).');
lines.push('-- Generated by scripts/seed-flats.ts. Re-runnable. Apply to the LOCAL');
lines.push('-- database only (psql -f seed-flats.sql). SVGs live in --svg-dir;');
lines.push('-- upload them to design-private at the storage_path recorded here');
lines.push('-- (the --supabase mode does that + the inserts in one step).');
lines.push(`-- tenant ${tenant}, base size ${size}`);
lines.push('BEGIN;');
lines.push(`DO $$ DECLARE lic uuid; BEGIN`);
lines.push(`  SELECT id INTO lic FROM public.ds_asset_licenses WHERE tenant_id = ${q(tenant)} AND source = 'generated' AND license_type = 'owned' ORDER BY created_at LIMIT 1;`);
lines.push(`  IF lic IS NULL THEN`);
lines.push(`    INSERT INTO public.ds_asset_licenses(tenant_id, source, license_type, license_name, allow_supplier_view, allow_redistribution)`);
lines.push(`    VALUES (${q(tenant)}, 'generated', 'owned', 'Atelier owned flat', true, false) RETURNING id INTO lic;`);
lines.push(`  END IF;`);
lines.push(`  PERFORM set_config('seed_flats.owned_license', lic::text, true);`);
lines.push(`END $$;`);
for (const { blank, views } of generated) {
  const printAreas: Record<string, unknown> = {};
  for (const v of views) {
    const pa = v.printAreas[v.view] as { nx: number; ny: number; nw: number; nh: number; widthMm: number; heightMm: number };
    printAreas[v.view] = { x: pa.nx, y: pa.ny, w: pa.nw, h: pa.nh, width_mm: pa.widthMm, height_mm: pa.heightMm };
  }
  const front = views[0];
  lines.push(`DO $$ DECLARE lic uuid := current_setting('seed_flats.owned_license')::uuid; front_asset uuid; BEGIN`);
  for (const v of views) {
    const path = `${tenant}/library/flats/${blank.id}/${v.view}.svg`;
    lines.push(`  INSERT INTO public.design_assets(tenant_id, kind, storage_path, bucket, classification, mime_type, license_id, metadata)`);
    lines.push(`  SELECT ${q(tenant)}, 'flat_sketch', ${q(path)}, 'design-private', 'internal', 'image/svg+xml', lic, ${q(JSON.stringify({ blank_id: blank.id, view: v.view, size, generator_version: GENERATOR_VERSION }))}::jsonb`);
    lines.push(`  WHERE NOT EXISTS (SELECT 1 FROM public.design_assets WHERE storage_path = ${q(path)});`);
    if (v.view === front.view) {
      lines.push(`  SELECT id INTO front_asset FROM public.design_assets WHERE storage_path = ${q(path)};`);
    }
  }
  lines.push(`  INSERT INTO public.ds_garment_templates(tenant_id, name, category, archetype, views, print_areas, flat_sketch_asset_id, license_id, block, style_options, generator_version)`);
  lines.push(`  VALUES (${q(tenant)}, ${q(blank.name)}, ${q(blank.category)}, ${q(blank.archetype)}, ARRAY[${blank.views.map((v: string) => q(v)).join(', ')}], ${q(JSON.stringify(printAreas))}::jsonb, front_asset, lic, ${q(JSON.stringify(blank.block))}::jsonb, ${q(JSON.stringify({ ...(blank.style as object), blank_id: blank.id }))}::jsonb, ${q(GENERATOR_VERSION)})`);
  lines.push(`  ON CONFLICT (tenant_id, name) DO UPDATE SET category = EXCLUDED.category, views = EXCLUDED.views, print_areas = EXCLUDED.print_areas, flat_sketch_asset_id = EXCLUDED.flat_sketch_asset_id, license_id = EXCLUDED.license_id, block = EXCLUDED.block, style_options = EXCLUDED.style_options, generator_version = EXCLUDED.generator_version;`);
  lines.push(`END $$;`);
}
lines.push(`SELECT count(*) AS seeded_owned_templates FROM public.ds_garment_templates WHERE tenant_id = ${q(tenant)} AND generator_version = ${q(GENERATOR_VERSION)};`);
lines.push('COMMIT;');
writeFileSync(sqlOut, lines.join('\n') + '\n');
console.log(`wrote ${sqlOut}`);
console.log(`svgs in ${svgDir}`);

if (useSupabase) {
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    console.error('SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY are required for --supabase mode.');
    process.exit(1);
  }
  const { createClient } = (await import('@supabase/supabase-js')) as typeof import('@supabase/supabase-js');
  const admin = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
  let { data: lic } = await admin
    .from('ds_asset_licenses')
    .select('id')
    .eq('tenant_id', tenant)
    .eq('source', 'generated')
    .eq('license_type', 'owned')
    .limit(1)
    .maybeSingle();
  if (!lic) {
    const ins = await admin.from('ds_asset_licenses').insert({
      tenant_id: tenant, source: 'generated', license_type: 'owned',
      license_name: 'Atelier owned flat', allow_supplier_view: true, allow_redistribution: false,
    }).select('id').single();
    if (ins.error) throw new Error(`license insert failed: ${ins.error.message}`);
    lic = ins.data;
  }
  for (const { blank, views } of generated) {
    const printAreas: Record<string, unknown> = {};
    let frontAsset: string | null = null;
    for (const v of views) {
      const pa = v.printAreas[v.view] as { nx: number; ny: number; nw: number; nh: number; widthMm: number; heightMm: number };
      printAreas[v.view] = { x: pa.nx, y: pa.ny, w: pa.nw, h: pa.nh, width_mm: pa.widthMm, height_mm: pa.heightMm };
      const path = `${tenant}/library/flats/${blank.id}/${v.view}.svg`;
      const up = await admin.storage.from('design-private').upload(path, new Blob([v.svg], { type: 'image/svg+xml' }), { upsert: true, contentType: 'image/svg+xml' });
      if (up.error) throw new Error(`upload ${path} failed: ${up.error.message}`);
      const ins = await admin.from('design_assets').insert({
        tenant_id: tenant, kind: 'flat_sketch', storage_path: path, bucket: 'design-private',
        classification: 'internal', mime_type: 'image/svg+xml', license_id: (lic as { id: string }).id,
        metadata: { blank_id: blank.id, view: v.view, size, generator_version: GENERATOR_VERSION },
      }).select('id').single();
      if (ins.error) throw new Error(`asset insert failed: ${ins.error.message}`);
      if (v.view === views[0].view) frontAsset = (ins.data as { id: string }).id;
    }
    const tpl = await admin.from('ds_garment_templates').upsert({
      tenant_id: tenant, name: blank.name, category: blank.category, archetype: blank.archetype,
      views: blank.views, print_areas: printAreas, flat_sketch_asset_id: frontAsset,
      license_id: (lic as { id: string }).id, block: blank.block,
      style_options: { ...(blank.style as object), blank_id: blank.id }, generator_version: GENERATOR_VERSION,
    }, { onConflict: 'tenant_id,name' }).select('id').single();
    if (tpl.error) throw new Error(`template upsert failed: ${tpl.error.message}`);
    console.log(`seeded ${blank.name} -> ${(tpl.data as { id: string }).id}`);
  }
  console.log('supabase seed complete');
}
